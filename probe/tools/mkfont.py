#!/usr/bin/env python3
"""Render Noto Sans Mono into 8-bit alpha atlases and write src/font_atlas.h.

Usage: mkfont.py FONT.ttf OUT.h
Glyphs: ASCII 32..126 laid out 16 per row in fixed cells (monospace).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = [("small", 15), ("large", 26)]

def build(path, px):
    font = ImageFont.truetype(path, px)
    try:
        font.set_variation_by_name("Regular")
    except Exception:
        pass
    asc, desc = font.getmetrics()
    adv = round(font.getlength("M"))
    cw, ch = adv, asc + desc
    cols, rows = 16, 6
    img = Image.new("L", (cols * cw, rows * ch), 0)
    d = ImageDraw.Draw(img)
    for c in range(32, 127):
        i = c - 32
        x, y = (i % cols) * cw, (i // cols) * ch
        d.text((x, y), chr(c), font=font, fill=255)
    return img, cw, ch, asc

def main():
    font_path, out = sys.argv[1], sys.argv[2]
    lines = ["/* Generated by tools/mkfont.py from Noto Sans Mono (SIL OFL 1.1). Do not edit. */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, px in SIZES:
        img, cw, ch, asc = build(font_path, px)
        w, h = img.size
        data = img.tobytes()
        lines.append(f"enum {{ FONT_{name.upper()}_W = {w}, FONT_{name.upper()}_H = {h}, "
                     f"FONT_{name.upper()}_CW = {cw}, FONT_{name.upper()}_CH = {ch} }};")
        lines.append(f"static const uint8_t font_{name}_pixels[{w*h}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i+24]) + ",")
        lines.append("};\n")
    open(out, "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
