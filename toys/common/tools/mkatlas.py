#!/usr/bin/env python3
"""Render a monospace font into an 8-bit alpha atlas for the toy's labels.

Usage: mkatlas.py FONT.ttf PIXEL_SIZE OUT.bin OUT.zig
Glyphs: ASCII 32..126, 16 per row, fixed cells. The last cell (index 95) is solid, for rectangles.
"""
import sys
from PIL import Image, ImageDraw, ImageFont


def main():
    font_path, px, out_bin, out_zig = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    font = ImageFont.truetype(font_path, px)
    asc, desc = font.getmetrics()
    cw, ch = round(font.getlength("M")), asc + desc
    cols, rows = 16, 6
    img = Image.new("L", (cols * cw, rows * ch), 0)
    d = ImageDraw.Draw(img)
    for c in range(32, 127):
        i = c - 32
        d.text(((i % cols) * cw, (i // cols) * ch), chr(c), font=font, fill=255)
    x0, y0 = (95 % cols) * cw, (95 // cols) * ch
    d.rectangle([x0, y0, x0 + cw - 1, y0 + ch - 1], fill=255)
    open(out_bin, "wb").write(img.tobytes())
    w, h = img.size
    open(out_zig, "w").write(
        "// Generated by tools/mkatlas.py. Do not edit.\n"
        f"pub const w = {w};\npub const h = {h};\npub const cw = {cw};\npub const ch = {ch};\n"
        f'pub const pixels = @embedFile("{out_bin.split("/")[-1]}");\n'
    )
    print(f"atlas {w}x{h}, cell {cw}x{ch}")


if __name__ == "__main__":
    main()
